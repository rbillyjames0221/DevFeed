import { getPrisma } from '@/lib/db/prisma';
import { requirePermission } from '@/lib/permissions';

export async function generateWeeklyStatusReport(userId: string, projectId: string) {
  await requirePermission(userId, projectId, 'report.generate');
  const db = getPrisma();
  const now = new Date();
  const dateStr = now.toISOString().slice(0, 10);
  const sevenDaysAgo = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000);
  const fourteenDaysAhead = new Date(now.getTime() + 14 * 24 * 60 * 60 * 1000);

  const [project, completedIssues, inProgressIssues, upcomingIssues] = await Promise.all([
    db.project.findUniqueOrThrow({
      where: { id: projectId },
      select: { name: true, issuePrefix: true }
    }),
    db.issue.findMany({
      where: {
        projectId,
        completedAt: { gte: sevenDaysAgo }
      },
      select: { issueKey: true, title: true, estimate: true, completedAt: true }
    }),
    db.issue.findMany({
      where: {
        projectId,
        archivedAt: null,
        status: { in: ['In Progress', 'IN_PROGRESS', 'Ready for QA', 'In Review'] }
      },
      select: { issueKey: true, title: true, status: true, assignee: { select: { username: true } } }
    }),
    db.issue.findMany({
      where: {
        projectId,
        archivedAt: null,
        targetDate: { gte: now, lte: fourteenDaysAhead }
      },
      select: { issueKey: true, title: true, targetDate: true, status: true },
      orderBy: { targetDate: 'asc' }
    })
  ]);

  const totalPointsCompleted = completedIssues.reduce((acc, i) => acc + (i.estimate ?? 1), 0);

  const markdown = `# Weekly Status Report — ${project.name}
**Date:** ${dateStr}  
**Generated by:** Automated System

---

## 1. Executive Summary
- **Tasks Shipped (Last 7 Days):** ${completedIssues.length} tasks (${totalPointsCompleted} points)
- **Active In-Flight Work:** ${inProgressIssues.length} tasks
- **Upcoming Deliveries (Next 14 Days):** ${upcomingIssues.length} tasks

---

## 2. Completed This Week
${
  completedIssues.length > 0
    ? completedIssues.map((i) => `- **${i.issueKey}**: ${i.title} (${i.estimate ?? 1} pts)`).join('\n')
    : '_No tasks completed in this window._'
}

---

## 3. Work In Progress
${
  inProgressIssues.length > 0
    ? inProgressIssues
        .map((i) => `- **${i.issueKey}** [${i.status}]: ${i.title} (${i.assignee?.username ?? 'Unassigned'})`)
        .join('\n')
    : '_No active tasks in progress._'
}

---

## 4. Upcoming Deadlines (Next 14 Days)
${
  upcomingIssues.length > 0
    ? upcomingIssues
        .map((i) => `- **${i.issueKey}**: ${i.title} — Due: ${i.targetDate?.toISOString().slice(0, 10)}`)
        .join('\n')
    : '_No deadlines scheduled in the next 14 days._'
}
`;

  // Save the report directly into Project Docs
  const slug = `weekly-report-${dateStr}`;
  const title = `Weekly Status Report (${dateStr})`;

  const doc = await db.docPage.upsert({
    where: { projectId_slug: { projectId, slug } },
    create: {
      projectId,
      slug,
      title,
      body: markdown,
      folder: 'Reports/Weekly',
      createdById: userId
    },
    update: {
      title,
      body: markdown
    }
  });

  return { docId: doc.id, slug: doc.slug, title: doc.title };
}
